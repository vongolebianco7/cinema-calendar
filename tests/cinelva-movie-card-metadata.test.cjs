assert.match(best10, /function movieMetadataLabel\(movie\)/);
assert.match(best10, /artworkTitleMode:document\.getElementById\("artworkTitleMode"\)\.value/);
assert.match(artwork, /function artworkMovieTitle\(movie\)/);
assert.match(artwork, /artValue\('artworkTitleMode'\)==='original'&&original/);
assert.match(artwork, /const title=artworkMovieTitle\(m\)/);
assert.match(artwork, /fittedLines\(ctx,title,/);
assert.match(artwork, /writeLines\(ctx,title,/);
assert.match(globalSearch, /x\.release_date\|\|x\.releaseDate\|\|x\.date/);
assert.match(globalSearch, /runtime>0\?runtime\+'分'/);
assert.match(globalSearch, /String\(x\.year\)\+'年'/);
assert.match(experience, /runtime\+'分'/);
assert.match(experience, /replaceAll\('-','\/'\)/);
console.log('Movie metadata and Best 10 title-mode contracts passed.');
