const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const identity = fs.readFileSync(path.join(root, 'js/cinelva-movie-identity.js'), 'utf8');
const best10 = fs.readFileSync(path.join(root, 'my-best10.html'), 'utf8');
const artwork = fs.readFileSync(path.join(root, 'js/my-cinemap-art.js'), 'utf8');
const globalSearch = fs.readFileSync(path.join(root, 'js/cinelva-global-search.js'), 'utf8');
const experience = fs.readFileSync(path.join(root, 'experience.html'), 'utf8');

assert.match(identity, /function movieMetadata\(m\)/);
assert.match(identity, /release_date \|\| m\?\.releaseDate \|\| m\?\.date/);
assert.match(identity, /Number\.isFinite\(runtime\) && runtime > 0/);
assert.match(identity, /m\?\.release_year \|\| m\?\.year/);
assert.match(identity, /function decorateMovieMetadata\(card, m\)/);
assert.match(identity, /decorateMovieMetadata\(card, movie\)/);
assert.match(identity, /movieMetadata,/);
assert.match(best10, /id="artworkTitleMode"/);
assert.match(best10, /value="japanese"/);
